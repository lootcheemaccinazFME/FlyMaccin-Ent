package com.flymaccin.lootcheerom
object TestRom {
    fun build():ByteArray {
        val rom=ByteArray(32*1024)
        // Entry point
        rom[0x100]=0xC3.toByte(); rom[0x101]=0x50; rom[0x102]=0x01
        val logo=intArrayOf(0xCE,0xED,0x66,0x66,0xCC,0x0D,0x00,0x0B,0x03,0x73,0x00,0x83,0x00,0x0C,0x00,0x0D,0x00,0x08,0x11,0x1F,0x88,0x89,0x00,0x0E,0xDC,0xCC,0x6E,0xE6,0xDD,0xDD,0xD9,0x99,0xBB,0xBB,0x67,0x63,0x6E,0x0E,0xEC,0xCC,0xDD,0xDC,0x99,0x9F,0xBB,0xB9,0x33,0x3E)
        logo.forEachIndexed{i,v->rom[0x104+i]=v.toByte()}
        "LOOTCHEE TEST".encodeToByteArray().copyInto(rom,0x134)
        rom[0x143]=0x00; rom[0x147]=0x00; rom[0x148]=0x00; rom[0x149]=0x00
        val code=mutableListOf<Int>(0xF3,0x31,0xFE,0xFF,0xAF,0xE0,0x40,0x21,0x00,0x80)
        repeat(8){ code += listOf(0x3E,0xAA,0x22,0x3E,0x55,0x22) }
        code += listOf(0x3E,0xE4,0xE0,0x47,0x3E,0x91,0xE0,0x40)
        // Read D-pad forever. Holding a direction changes the background palette.
        code += listOf(0x3E,0x20,0xE0,0x00,0xF0,0x00,0x2F,0xE6,0x0F,0xF6,0xE0,0xE0,0x47,0x18,0xF1)
        code.forEachIndexed{i,v->rom[0x150+i]=v.toByte()}
        var x=0
        for(i in 0x134..0x14C) x=(x-(rom[i].toInt() and 0xff)-1) and 0xff
        rom[0x14D]=x.toByte()
        var sum=0
        for(i in rom.indices) if(i!=0x14E&&i!=0x14F) sum=(sum+(rom[i].toInt() and 0xff)) and 0xffff
        rom[0x14E]=(sum shr 8).toByte(); rom[0x14F]=sum.toByte()
        return rom
    }
}
